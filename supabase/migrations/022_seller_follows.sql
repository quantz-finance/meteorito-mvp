-- 022: seguir vendedores (privado). Idempotente: se puede correr más de una vez.
-- follower_id: quién sigue. sub de la cuenta (Cavos) o, para compradores sin cuenta, 'guest:' + hash de la llave del
--   dispositivo (api/_lib/guest.ts). La llave cruda NUNCA se guarda.
-- Privacidad: solo el servicio (service role) lee y escribe. Al público solo le llega el NÚMERO de seguidores
--   (GET /api/store?profile), nunca quién sigue a quién. Sin grants para anon/authenticated.
create table if not exists public.seller_follows (
  id             bigint generated by default as identity primary key,
  follower_id    text not null check (char_length(follower_id) between 3 and 120),
  seller_user_id text not null check (char_length(seller_user_id) between 1 and 200),
  created_at     timestamptz not null default now(),
  constraint seller_follows_not_self check (follower_id <> seller_user_id)
);
-- Un seguimiento por par (seguir dos veces no duplica).
create unique index if not exists seller_follows_pair_uidx on public.seller_follows (follower_id, seller_user_id);
-- Contar seguidores de un vendedor y avisarles cuando publica.
create index if not exists seller_follows_seller_idx on public.seller_follows (seller_user_id, created_at desc);
alter table public.seller_follows enable row level security;
revoke all on public.seller_follows from anon, authenticated;

-- Anti-spam en la base (además del límite por minuto del API): máximo 500 vendedores seguidos por identidad.
create or replace function public.seller_follows_cap() returns trigger language plpgsql as $$
begin
  if (select count(*) from public.seller_follows where follower_id = new.follower_id) >= 500 then
    raise exception 'follow_limit' using errcode = 'P0001';
  end if;
  return new;
end $$;
drop trigger if exists seller_follows_cap_trg on public.seller_follows;
create trigger seller_follows_cap_trg before insert on public.seller_follows
  for each row execute function public.seller_follows_cap();

notify pgrst, 'reload schema';
