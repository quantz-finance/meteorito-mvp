-- 023: bloque "Patrocinado" del feed de Comprar. Idempotente: se puede correr más de una vez.
-- Publicidad identificable (Ley 7472): la app SIEMPRE los muestra con la etiqueta "Patrocinado", en su propio bloque.
-- Todavía no hay pago del vendedor en la app: un admin activa cada patrocinio por SQL (ver ejemplos abajo).
-- Sin esta tabla, o sin patrocinios activos, el bloque no aparece (nunca hay anuncios de relleno).
create table if not exists public.sponsored_listings (
  id              bigint generated by default as identity primary key,
  order_slug      text not null references public.orders (slug) on delete cascade, -- producto permanente (kind 'listing')
  seller_user_id  text not null,                                                   -- dueño del producto (se valida al mostrar)
  starts_at       timestamptz not null default now(),
  ends_at         timestamptz not null,
  status          text not null default 'activa' check (status in ('activa', 'pausada', 'terminada', 'cancelada')),
  amount_paid_crc bigint not null default 0 check (amount_paid_crc >= 0),           -- lo que pagó el vendedor (fuera de la app por ahora)
  notes           text check (notes is null or char_length(notes) <= 500),
  created_at      timestamptz not null default now(),
  constraint sponsored_listings_window check (ends_at > starts_at)
);
-- Un solo patrocinio activo por producto.
create unique index if not exists sponsored_listings_one_active_uidx on public.sponsored_listings (order_slug) where status = 'activa';
create index if not exists sponsored_listings_live_idx on public.sponsored_listings (status, ends_at, starts_at);
alter table public.sponsored_listings enable row level security;
revoke all on public.sponsored_listings from anon, authenticated;

