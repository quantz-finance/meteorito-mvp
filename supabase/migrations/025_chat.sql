-- 025: chat comprador-vendedor (antes de comprar, con la tienda o un producto; y dentro de una compra, por pedido).
-- Idempotente: se puede correr más de una vez. NO la aplica el deploy: se corre a mano en el SQL Editor de Supabase.
-- Privacidad: solo el servicio (service role, /api/store acciones chat_*) lee y escribe. RLS encendido y sin grants para
--   anon/authenticated: nadie lee mensajes con la llave pública. La app NO usa Supabase Realtime (polling vía /api/store),
--   así que no hace falta ninguna política ni publicación de Realtime.
-- Identidades: seller_user_id = sub de Cavos del vendedor; buyer_id = sub de Cavos o 'guest:' + hash de la llave del
--   dispositivo (api/_lib/guest.ts). La llave cruda NUNCA se guarda.
-- token: 32 caracteres aleatorios (base64url). Es lo único que viaja en links y avisos; el id interno nunca sale del servidor.
-- Retención: 12 meses desde el último mensaje (propuesta, pendiente de revisión legal); job diario con pg_cron si existe.

create extension if not exists pgcrypto;

create table if not exists public.chat_conversations (
  id               uuid primary key default gen_random_uuid(),
  token            text not null unique check (token ~ '^[A-Za-z0-9_-]{32}$'),
  seller_user_id   text not null check (char_length(seller_user_id) between 1 and 200),
  buyer_id         text not null check (char_length(buyer_id) between 3 and 200),
  -- 'store' (antes de comprar) u 'order:<slug>' (dentro de una compra). Una conversación por comprador, vendedor y contexto.
  ctx              text not null check (ctx = 'store' or ctx ~ '^order:[a-z0-9]{6}$'),
  order_slug       text check (order_slug is null or order_slug ~ '^[a-z0-9]{6}$'),
  item_slug        text check (item_slug is null or item_slug ~ '^[a-z0-9]{6}$'),
  subject          text check (subject is null or char_length(subject) <= 120),
  item_photo       text check (item_photo is null or char_length(item_photo) <= 600),
  blocked_at       timestamptz,
  created_at       timestamptz not null default now(),
  last_message_at  timestamptz,
  last_sender      text check (last_sender is null or last_sender in ('buyer', 'seller')),
  last_preview     text check (last_preview is null or char_length(last_preview) <= 200),
  buyer_read_at    timestamptz,
  seller_read_at   timestamptz,
  buyer_seen_at    timestamptz,
  seller_seen_at   timestamptz,
  buyer_typing_at  timestamptz,
  seller_typing_at timestamptz,
  buyer_pushed_at  timestamptz,
  seller_pushed_at timestamptz,
  constraint chat_conversations_not_self check (buyer_id <> seller_user_id)
);
create unique index if not exists chat_conversations_pair_uidx on public.chat_conversations (buyer_id, seller_user_id, ctx);
-- Bandejas: del vendedor y del comprador, lo más reciente primero.
create index if not exists chat_conversations_seller_idx on public.chat_conversations (seller_user_id, last_message_at desc nulls last);
create index if not exists chat_conversations_buyer_idx on public.chat_conversations (buyer_id, last_message_at desc nulls last);
create index if not exists chat_conversations_retention_idx on public.chat_conversations ((coalesce(last_message_at, created_at)));

create table if not exists public.chat_messages (
  id              bigint generated by default as identity primary key,
  conversation_id uuid not null references public.chat_conversations (id) on delete cascade,
  sender          text not null check (sender in ('buyer', 'seller')),
  body            text not null check (char_length(body) between 1 and 1000),
  client_id       text check (client_id is null or client_id ~ '^[A-Za-z0-9_-]{8,40}$'),
  created_at      timestamptz not null default now()
);
-- Leer una conversación por páginas y el polling "lo nuevo después de <id>".
create index if not exists chat_messages_conv_idx on public.chat_messages (conversation_id, id);
-- Límite por minuto por lado (api/_lib/chat.ts).
create index if not exists chat_messages_rate_idx on public.chat_messages (conversation_id, sender, created_at desc);
-- Envío optimista idempotente: el mismo client_id no duplica el mensaje.
create unique index if not exists chat_messages_client_uidx on public.chat_messages (conversation_id, client_id) where client_id is not null;

create table if not exists public.chat_reports (
  id              bigint generated by default as identity primary key,
  conversation_id uuid not null references public.chat_conversations (id) on delete cascade,
  reporter_role   text not null check (reporter_role in ('buyer', 'seller')),
  reason          text not null check (reason in ('spam', 'abuso', 'fraude', 'otro')),
  detail          text check (detail is null or char_length(detail) <= 300),
  created_at      timestamptz not null default now(),
  reviewed_at     timestamptz
);
-- Un reporte por lado y conversación.
create unique index if not exists chat_reports_once_uidx on public.chat_reports (conversation_id, reporter_role);

alter table public.chat_conversations enable row level security;
alter table public.chat_messages enable row level security;
alter table public.chat_reports enable row level security;
revoke all on public.chat_conversations from anon, authenticated;
revoke all on public.chat_messages from anon, authenticated;
revoke all on public.chat_reports from anon, authenticated;

-- Retención: borra conversaciones (y por cascada sus mensajes y reportes) sin mensajes desde hace 12 meses.
create or replace function public.chat_purge_old() returns bigint
language sql security definer set search_path = public as $$
  with gone as (
    delete from public.chat_conversations where coalesce(last_message_at, created_at) < now() - interval '12 months' returning 1
  ) select count(*) from gone;
$$;
revoke all on function public.chat_purge_old() from public, anon, authenticated;

do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.unschedule(jobid) from cron.job where jobname = 'meteorito-chat-retention';
    perform cron.schedule('meteorito-chat-retention', '17 4 * * *', 'select public.chat_purge_old()');
  end if;
end $$;

notify pgrst, 'reload schema';
