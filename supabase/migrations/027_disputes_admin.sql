-- 027: panel admin de disputas (auditoría de decisiones, caché del resumen con IA, respuesta del vendedor y flags).
-- Idempotente: se puede correr más de una vez. NO la aplica el deploy: se corre a mano en el SQL Editor de Supabase
--   (después de 025; no depende de 026). La app funciona SIN esta migración (degrada): sin respuesta del vendedor en la
--   app (la regla de 48 h no aplica), sin caché de IA, flags solo por env y la auditoría queda en order_events.
-- Privacidad: solo el servicio (service role, /api/escrow/dispute) lee y escribe. RLS encendido y sin grants para
--   anon/authenticated.

-- ---------- Auditoría: quién decidió, cuándo, por qué y qué pasó on-chain ----------
create table if not exists public.dispute_decisions (
  id                bigint generated by default as identity primary key,
  order_id          uuid not null references public.orders(id),
  slug              text not null check (slug ~ '^[a-z0-9]{6}$'),
  decided_by        text not null check (char_length(decided_by) between 1 and 200),  -- sub de Cavos del admin, 'script' o 'auto'
  decided_by_email  text check (decided_by_email is null or char_length(decided_by_email) <= 200),
  source            text not null default 'admin' check (source in ('admin', 'script', 'auto_rule')),
  outcome           text not null check (outcome in ('refund', 'release', 'split')),
  buyer_pct         integer not null check (buyer_pct between 0 and 100),
  note              text not null check (char_length(note) between 1 and 1000),
  rule_id           text check (rule_id is null or char_length(rule_id) <= 40),
  ai_recommendation text check (ai_recommendation is null or char_length(ai_recommendation) <= 40),
  status            text not null check (status in ('executing', 'executed', 'failed', 'pending_onchain')),
  resolved_tx       text,
  to_buyer          numeric,
  to_seller         numeric,
  error             text check (error is null or char_length(error) <= 300),
  -- Comprador invitado: su parte llega a la wallet 'platform' y se le devuelve por fuera (docs/guest-checkout.md).
  guest_refund      text check (guest_refund is null or guest_refund in ('no_aplica', 'pendiente', 'devuelto')),
  guest_refund_note text check (guest_refund_note is null or char_length(guest_refund_note) <= 500),
  guest_refunded_at timestamptz,
  guest_refunded_by text,
  created_at        timestamptz not null default now(),
  executed_at       timestamptz
);
create index if not exists dispute_decisions_order_idx on public.dispute_decisions (order_id, created_at desc);
create index if not exists dispute_decisions_guest_idx on public.dispute_decisions (guest_refund) where guest_refund = 'pendiente';

-- ---------- Caché del resumen con IA (uno por disputa; se regenera si cambia el hash de la entrada) ----------
create table if not exists public.dispute_ai_summaries (
  order_id    uuid primary key references public.orders(id),
  input_hash  text not null check (char_length(input_hash) between 8 and 64),
  model       text check (model is null or char_length(model) <= 100),
  result      jsonb not null,
  created_at  timestamptz not null default now()
);

-- ---------- Respuesta del vendedor (texto + foto de la cámara de la app) ----------
create table if not exists public.dispute_responses (
  order_id        uuid primary key references public.orders(id),
  seller_user_id  text not null check (char_length(seller_user_id) between 1 and 200),
  body            text not null check (char_length(body) between 1 and 1000),
  photo           text check (photo is null or char_length(photo) <= 600),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

-- ---------- Flags (auto-resolución apagada por defecto) ----------
create table if not exists public.app_flags (
  key         text primary key check (key ~ '^[a-z0-9_]{2,60}$'),
  value       jsonb not null,
  updated_at  timestamptz not null default now(),
  updated_by  text
);
insert into public.app_flags (key, value) values ('disputes_auto_resolve', 'false'::jsonb) on conflict (key) do nothing;
insert into public.app_flags (key, value) values ('disputes_ai', 'true'::jsonb) on conflict (key) do nothing;

alter table public.dispute_decisions enable row level security;
alter table public.dispute_ai_summaries enable row level security;
alter table public.dispute_responses enable row level security;
alter table public.app_flags enable row level security;
revoke all on public.dispute_decisions from anon, authenticated;
revoke all on public.dispute_ai_summaries from anon, authenticated;
revoke all on public.dispute_responses from anon, authenticated;
revoke all on public.app_flags from anon, authenticated;

notify pgrst, 'reload schema';
